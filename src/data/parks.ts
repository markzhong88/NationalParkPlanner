export function parksByPopularity(): ParkProfile[] {
  return [...PARKS].sort(
    (a, b) =>
      (PARK_RANK[a.id] ?? 100) - (PARK_RANK[b.id] ?? 100) ||
      (PARK_VISITORS[b.id] ?? 0) - (PARK_VISITORS[a.id] ?? 0) ||
      a.shortName.localeCompare(b.shortName),
  );
}

export const PARKS_BY_POPULARITY = parksByPopularity();

export function getPark(id: string): ParkProfile | undefined {
  const park = PARKS.find((p) => p.id === id);
  if (!park) return undefined;
  const extra = EXTRA_VIEWPOINTS[id] ?? [];
  if (!extra.length) return park;
  const seen = new Set(park.landmarks.map((l) => l.id));
  return {
    ...park,
    landmarks: [...park.landmarks, ...extra.filter((l) => !seen.has(l.id))],
  };
}
